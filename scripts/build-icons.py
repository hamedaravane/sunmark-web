#!/usr/bin/env python3
"""Build the reviewed local SVG atlas without network access or imaging dependencies."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((ROOT / 'scripts/icon-manifest.json').read_text())
source_path = ROOT / 'art/reference/icons/fluent-emoji-flat.json'
source = json.loads(source_path.read_text())
columns, cell = 8, 128
rows = (len(manifest) + columns - 1) // columns
parts = []
for i, (role, upstream) in enumerate(manifest.items()):
    art = source['icons'][upstream]
    body = art['body']
    # Prevent collisions if a selected upstream drawing has local gradient/clip IDs.
    ids = re.findall(r'id="([^"]+)"', body)
    for name in ids:
        body = body.replace(f'id="{name}"', f'id="{role}-{name}"')
        body = body.replace(f'url(#{name})', f'url(#{role}-{name})')
        body = body.replace(f'href="#{name}"', f'href="#{role}-{name}"')
    width, height = art.get('width', 32), art.get('height', 32)
    parts.append(f'<svg id="{role}" x="{i % columns * cell}" y="{i // columns * cell}" width="{cell}" height="{cell}" viewBox="0 0 {width} {height}">{body}</svg>')
atlas = f'<svg xmlns="http://www.w3.org/2000/svg" width="{columns * cell}" height="{rows * cell}" viewBox="0 0 {columns * cell} {rows * cell}">\n<!-- Fluent Emoji Flat. Copyright Microsoft Corporation. MIT; see license.txt. -->\n' + '\n'.join(parts) + '\n</svg>\n'
css = f"""/* Generated by scripts/build-icons.py; uses the same atlas as Phaser. */
.game-icon {{
    display: inline-block;
    flex: none;
    vertical-align: middle;
    background-image: url('/assets/ui/icons/fluent.svg');
    background-size: {columns * 100}% {rows * 100}%;
    background-repeat: no-repeat;
}}

.game-icon[data-icon='profile'],
.game-icon[data-icon='friends'],
.game-icon[data-icon='road'] {{
    background-color: #ffefd4;
    border-radius: 8px;
}}
"""
for size in range(12, 129):
    css += f'\n.game-icon--{size} {{\n    width: {size}px;\n    height: {size}px;\n}}\n'
for i, role in enumerate(manifest):
    x = f'{i % columns / (columns - 1) * 100:.6f}'.rstrip('0').rstrip('.')
    y = f'{i // columns / (rows - 1) * 100:.6f}'.rstrip('0').rstrip('.')
    css += f"\n.game-icon[data-icon='{role}'] {{\n    background-position: {x}% {y}%;\n}}\n"
names = ',\n'.join(f"    '{role}'" for role in manifest)
ts = f"""// Generated by scripts/build-icons.py; edit scripts/icon-manifest.json instead.
export const ICON_NAMES = [
{names},
] as const;
export type IconName = (typeof ICON_NAMES)[number];
export const ICON_COLUMNS = {columns};
export const ICON_ROWS = {rows};
export const ICON_CELL = {cell};
export const ICON_SOURCE_SHA256 =
    '{hashlib.sha256(source_path.read_bytes()).hexdigest()}';
"""
for name, content in {'public/assets/ui/icons/fluent.svg': atlas, 'src/ui/iconManifest.ts': ts, 'src/ui/icons.css': css}.items():
    path = ROOT / name
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'Icon output is stale: {name}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
print(f'{len(manifest)} semantic icons, {len(set(manifest.values()))} upstream drawings, {len(atlas.encode())} SVG bytes; {columns * cell}x{rows * cell} shared texture')
